// An icon's name comes from a file and may be any text, so only the catalogue's own entries count.
export const iconNamed = (name: string | undefined): LucideIcon | undefined =>
  name !== undefined && Object.keys(iconChoices).includes(name) ? iconChoices[name] : undefined;

export const iconFor = (name: string | undefined, fallback: LucideIcon): LucideIcon => iconNamed(name) ?? fallback;
